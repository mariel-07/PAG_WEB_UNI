function initNavegacion() {

    const botones =
        document.querySelectorAll(
            ".seccion-nav"
        );


    const secciones =
        document.querySelectorAll(
            ".seccion-docente"
        );


    const btnAnterior =
        document.getElementById(
            "btnAnterior"
        );


    const btnSiguiente =
        document.getElementById(
            "btnSiguiente"
        );


    const seccionActual =
        document.getElementById(
            "seccionActual"
        );


    let actual = 1;

    const total = 4;


    function mostrarSeccion(numero) {

        actual = numero;


        secciones.forEach(
            seccion => {

                seccion.classList.remove(
                    "seccion-activa"
                );
            }
        );


        document
            .getElementById(
                `seccion-${numero}`
            )
            ?.classList.add(
                "seccion-activa"
            );


        botones.forEach(
            btn => {

                btn.classList.remove(
                    "activo"
                );


                if (
                    Number(
                        btn.dataset.seccion
                    ) === numero
                ) {

                    btn.classList.add(
                        "activo"
                    );
                }
            }
        );


        if (seccionActual) {

            seccionActual.textContent =
                String(numero)
                    .padStart(2, "0");
        }


        if (btnAnterior) {

            btnAnterior.disabled =
                numero === 1;
        }


        if (btnSiguiente) {

            btnSiguiente.disabled =
                numero === total;
        }


        window.scrollTo({
            top: 0,
            behavior: "smooth"
        });
    }


    botones.forEach(
        btn => {

            btn.addEventListener(
                "click",
                function () {

                    mostrarSeccion(
                        Number(
                            this.dataset.seccion
                        )
                    );
                }
            );
        }
    );


    if (btnAnterior) {

        btnAnterior.addEventListener(
            "click",
            function () {

                if (actual > 1) {

                    mostrarSeccion(
                        actual - 1
                    );
                }
            }
        );
    }


    if (btnSiguiente) {

        btnSiguiente.addEventListener(
            "click",
            function () {

                if (actual < total) {

                    mostrarSeccion(
                        actual + 1
                    );
                }
            }
        );
    }


    mostrarSeccion(1);
}


