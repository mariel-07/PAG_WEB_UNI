/* ============================================================
   GENERAR PDF COMPLETO
============================================================ */

async function generarPDFDocente() {

    if (
        typeof html2pdf ===
        'undefined'
    ) {

        alert(
            'Error: La librería html2pdf.js no está disponible.'
        );

        return;

    }


    const boton =
        document.getElementById(
            'btnGenerarPDF'
        );


    if (boton) {

        boton.disabled =
            true;


        boton.innerHTML = `

            <i
                class="fas fa-spinner fa-spin me-2"
            ></i>

            Generando ficha...

        `;

    }


    try {

        /* ====================================================
           OBTENER DATOS ACTUALES
        ==================================================== */

        const personales =
            datosPersonales || {};


        const domicilios =
            datosDomicilio || [];


        const familiares =
            datosFamiliares || [];


        const formaciones =
            datosFormacion || [];


        /* ====================================================
           CREAR REPORTE
        ==================================================== */

        const reporte =
            document.createElement(
                'div'
            );


        reporte.id =
            'reportePDFDocente';


        reporte.innerHTML =
            construirReportePDF(
                personales,
                domicilios,
                familiares,
                formaciones
            );


        /* ====================================================
           AGREGAR ESTILOS
        ==================================================== */

        agregarEstilosPDF();


        /* ====================================================
           INSERTAR
        ==================================================== */

        document.body.appendChild(
            reporte
        );


        /* ====================================================
           ESPERAR RENDERIZADO
        ==================================================== */

        await new Promise(
            resolve =>
                setTimeout(
                    resolve,
                    500
                )
        );


        /* ====================================================
           NOMBRE
        ==================================================== */

        const nombreDocente =
            obtenerNombreDocente(
                personales
            );


        const nombreArchivo =
            `Ficha_Docente_UNI_${nombreDocente}.pdf`;


        /* ====================================================
           OPCIONES PDF
        ==================================================== */

        const opciones = {

            margin: [
                10,
                10,
                15,
                10
            ],


            filename:
                nombreArchivo,


            image: {

                type:
                    'jpeg',

                quality:
                    0.98

            },


            html2canvas: {

                scale:
                    2,

                useCORS:
                    true,

                allowTaint:
                    true,

                logging:
                    false,

                backgroundColor:
                    '#ffffff'

            },


            pagebreak: {

                mode: [
                    'css',
                    'legacy'
                ],

                avoid: [
                    'tr',
                    '.tarjeta-pdf',
                    '.encabezado-seccion-pdf'
                ]

            },


            jsPDF: {

                unit:
                    'mm',

                format:
                    'a4',

                orientation:
                    'portrait',

                compress:
                    true

            }

        };


        /* ====================================================
           GENERAR
        ==================================================== */

        await html2pdf()
            .set(opciones)
            .from(reporte)
            .save();


        /* ====================================================
           ELIMINAR REPORTE TEMPORAL
        ==================================================== */

        reporte.remove();


        /* ====================================================
           MENSAJE
        ==================================================== */

        mostrarMensaje(

            'PDF generado correctamente',

            'La ficha docente completa fue generada con las 4 secciones.'

        );


    } catch (error) {

        console.error(
            'Error al generar PDF:',
            error
        );


        const reporte =
            document.getElementById(
                'reportePDFDocente'
            );


        if (reporte) {

            reporte.remove();

        }


        alert(
            'Ocurrió un error al generar el PDF.'
        );

    }


    finally {

        if (boton) {

            boton.disabled =
                false;


            boton.innerHTML = `

                <i
                    class="fas fa-file-pdf me-2"
                ></i>

                Generar PDF

            `;

        }

    }

}


