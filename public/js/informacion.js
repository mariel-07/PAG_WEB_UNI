/* ============================================================
   FORMATEAR FECHA
============================================================ */

function formatearFecha(
    fecha
) {

    if (
        !fecha ||
        fecha === '-' ||
        fecha === 'null' ||
        fecha === 'undefined'
    ) {

        return '-';

    }


    const partes =
        String(fecha).split('-');


    if (
        partes.length === 3
    ) {

        return `
            ${partes[2]}/
            ${partes[1]}/
            ${partes[0]}
        `;

    }


    return fecha;

}


/* ============================================================
   OBTENER NOMBRE DOCENTE
============================================================ */

function obtenerNombreDocente(
    personales
) {

    const nombre =
        personales.nombreCompleto ||
        personales.nombre ||
        personales.nombres ||
        '';


    const apellidos =
        personales.apellidos ||
        '';


    if (
        nombre ||
        apellidos
    ) {

        return `${nombre} ${apellidos}`
            .trim()
            .replace(
                /\s+/g,
                '_'
            )
            .replace(
                /[^a-zA-Z0-9áéíóúÁÉÍÓÚñÑ_-]/g,
                ''
            );

    }


    if (
        personales.dni
    ) {

        return `DNI_${personales.dni}`;

    }


    return 'Docente';

}


/* ============================================================
   ESCAPAR HTML
============================================================ */

function escapeHTML(
    valor
) {

    if (
        valor === undefined ||
        valor === null
    ) {

        return '-';

    }


    return String(valor)

        .replace(
            /&/g,
            '&amp;'
        )

        .replace(
            /</g,
            '&lt;'
        )

        .replace(
            />/g,
            '&gt;'
        )

        .replace(
            /"/g,
            '&quot;'
        )

        .replace(
            /'/g,
            '&#039;'
        );

}


