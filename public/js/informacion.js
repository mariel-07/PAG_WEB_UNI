function normalizarFechaInput(
    fecha
) {

    if (
        !fecha ||
        fecha === "-" ||
        fecha === "null"
    ) {

        return "";
    }


    return String(fecha)
        .substring(0, 10);
}


function formatearFecha(
    fecha
) {

    if (
        !fecha ||
        fecha === "-" ||
        fecha === "null"
    ) {

        return "-";
    }


    const partes =
        String(fecha)
            .substring(0, 10)
            .split("-");


    if (
        partes.length === 3
    ) {

        return `${partes[2]}/${partes[1]}/${partes[0]}`;
    }


    return fecha;
}


function obtenerSexoTexto(
    sexo
) {

    if (
        sexo === "M" ||
        sexo === "Masculino"
    ) {

        return "Masculino";
    }


    if (
        sexo === "F" ||
        sexo === "Femenino"
    ) {

        return "Femenino";
    }


    return sexo || "-";
}


function obtenerNombreDocente() {

    const nombres =
        datosPersonales.nombres ||
        "";


    const apePaterno =
        datosPersonales.apePaterno ||
        "";


    const apeMaterno =
        datosPersonales.apeMaterno ||
        "";


    const nombreCompleto =
        `${apePaterno} ${apeMaterno}, ${nombres}`
            .trim();


    return nombreCompleto ||
        "Docente";
}


function escapeHTML(
    valor
) {

    if (
        valor === null ||
        valor === undefined
    ) {

        return "";
    }


    return String(valor)

        .replace(
            /&/g,
            "&amp;"
        )

        .replace(
            /</g,
            "&lt;"
        )

        .replace(
            />/g,
            "&gt;"
        )

        .replace(
            /"/g,
            "&quot;"
        )

        .replace(
            /'/g,
            "&#039;"
        );
}


