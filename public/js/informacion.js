/* =========================================================
FETCH GENERAL
========================================================= */

async function enviarSolicitud(
    url,
    metodo = "GET",
    datos = null
) {

    const opciones = {

        method: metodo,

        headers: {
            "Accept": "application/json",
            "X-Requested-With": "XMLHttpRequest",
            "X-CSRF-TOKEN": obtenerCSRF()
        },

        credentials: "same-origin"
    };


    if (datos !== null) {

        opciones.headers["Content-Type"] =
            "application/json";

        opciones.body =
            JSON.stringify(datos);
    }


    const response =
        await fetch(
            url,
            opciones
        );


    let resultado = {};

    try {

        resultado =
            await response.json();

    } catch (error) {

        resultado = {};
    }


    if (!response.ok) {

        let mensaje =
            resultado.message ||
            resultado.error ||
            `Error HTTP ${response.status}`;


        if (resultado.errors) {

            mensaje =
                Object.values(
                    resultado.errors
                )
                .flat()
                .join("<br>");
        }


        throw new Error(mensaje);
    }


    return resultado;
}


/* =========================================================
FETCH PARA FORMDATA
========================================================= */

async function enviarFormData(
    url,
    formData
) {

    const response =
        await fetch(
            url,
            {
                method: "POST",

                headers: {
                    "Accept":
                        "application/json",

                    "X-Requested-With":
                        "XMLHttpRequest",

                    "X-CSRF-TOKEN":
                        obtenerCSRF()
                },

                body:
                    formData,

                credentials:
                    "same-origin"
            }
        );


    let resultado = {};

    try {

        resultado =
            await response.json();

    } catch (error) {

        resultado = {};
    }


    if (!response.ok) {

        let mensaje =
            resultado.message ||
            resultado.error ||
            "Ocurrió un error.";


        if (resultado.errors) {

            mensaje =
                Object.values(
                    resultado.errors
                )
                .flat()
                .join("<br>");
        }


        throw new Error(mensaje);
    }


    return resultado;
}


