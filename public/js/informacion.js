/* ============================================================
   CARGAR DATOS DESDE JSON
============================================================ */

async function cargarDatosDesdeJSON() {

    try {

        const response =
            await fetch(
                '/json/informacion.json',
                {
                    cache: 'no-store'
                }
            );


        if (!response.ok) {

            throw new Error(
                `Error HTTP: ${response.status}`
            );

        }


        const data =
            await response.json();


        /* ====================================================
           DATOS PERSONALES
        ==================================================== */

        datosPersonales =
            data.datos_personales || {};


        /* ====================================================
           DOMICILIOS
        ==================================================== */

        const domiciliosJSON =
            (data.domicilios || [])
                .map(
                    (dom, index) => {

                        return {

                            id:
                                dom.id ||
                                Date.now() +
                                index,

                            pais:
                                dom.pais ||
                                '-',

                            dirExt:
                                dom.direccionExt ||
                                '-',

                            dep:
                                dom.departamento ||
                                '-',

                            prov:
                                dom.provincia ||
                                '-',

                            dist:
                                dom.distrito ||
                                '-',

                            tipoVia:
                                dom.tipoVia ||
                                '-',

                            nombreVia:
                                dom.nombreVia ||
                                '-',

                            tipoInmueble:
                                dom.tipoInm ||
                                '-',

                            numeroInmueble:
                                dom.nroInmueble ||
                                '-'

                        };

                    }
                );


        /* ====================================================
           FAMILIARES
        ==================================================== */

        const familiaresJSON =
            (data.familiares || [])
                .map(
                    (fam, index) => {

                        return {

                            id:
                                fam.id ||
                                Date.now() +
                                index,

                            nombre:
                                fam.nombre ||
                                '-',

                            parentesco:
                                fam.parentesco ||
                                '-',

                            fecNac:
                                fam.fecNac ||
                                '-',

                            estCivil:
                                fam.estCivil ||
                                '-',

                            estudios:
                                fam.estudios ||
                                '-',

                            ocupacion:
                                fam.ocupacion ||
                                '-',

                            celular:
                                fam.celular ||
                                '-',

                            depende:
                                fam.depende ||
                                'No'

                        };

                    }
                );


        /* ====================================================
           FORMACIÓN PROFESIONAL
        ==================================================== */

        const formacionJSON =
            (data.formacion_profesional || [])
                .map(
                    (form, index) => {

                        return {

                            id:
                                form.id ||
                                Date.now() +
                                index,

                            nivel:
                                form.formacion ||
                                '-',

                            pais:
                                form.pais ||
                                'Perú',

                            universidad:
                                form.universidad ||
                                '-',

                            especialidad:
                                form.especialidad ||
                                '-',

                            fecInicio:
                                form.inicio ||
                                '-',

                            fecFinal:
                                form.fin ||
                                '-',

                            grado:
                                form.grado ||
                                '-',

                            tieneDoc:
                                !!form.doc,

                            docBase64:
                                '',

                            nombreDoc:
                                form.doc ||
                                '',

                            obs:
                                form.obs ||
                                '-'

                        };

                    }
                );


        /* ====================================================
           LOCAL STORAGE
        ==================================================== */

        const familiaresGuardados =
            localStorage.getItem(
                'docente_familiares'
            );


        const domiciliosGuardados =
            localStorage.getItem(
                'docente_domicilios'
            );


        const formacionGuardada =
            localStorage.getItem(
                'docente_formacion'
            );


        const personalesGuardados =
            localStorage.getItem(
                'docente_personales'
            );


        /* ====================================================
           DECIDIR DATOS
        ==================================================== */

        datosDomicilio =
            domiciliosGuardados
                ? JSON.parse(
                    domiciliosGuardados
                )
                : domiciliosJSON;


        datosFamiliares =
            familiaresGuardados
                ? JSON.parse(
                    familiaresGuardados
                )
                : familiaresJSON;


        datosFormacion =
            formacionGuardada
                ? JSON.parse(
                    formacionGuardada
                )
                : formacionJSON;


        if (personalesGuardados) {

            datosPersonales = {

                ...datosPersonales,

                ...JSON.parse(
                    personalesGuardados
                )

            };

        }


        console.log(
            '===================================='
        );

        console.log(
            'DATOS CARGADOS'
        );

        console.log(
            '===================================='
        );

        console.log(
            'Datos personales:',
            datosPersonales
        );

        console.log(
            'Domicilios:',
            datosDomicilio
        );

        console.log(
            'Familiares:',
            datosFamiliares
        );

        console.log(
            'Formación:',
            datosFormacion
        );


    } catch (error) {

        console.error(
            'No se pudo cargar informacion.json:',
            error
        );


        alert(
            'Error: No se pudo cargar el archivo de información JSON.'
        );

    }

}


